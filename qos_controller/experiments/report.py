    static_qos = comparisons.get("static_qos", {})
    adaptive = comparisons.get("adaptive_qos", {})

    rows_html = []
    all_keys = list(dict.fromkeys(list(no_qos) + list(static_qos) + list(adaptive)))
    for k in all_keys:
        v_no = no_qos.get(k, "N/A")
