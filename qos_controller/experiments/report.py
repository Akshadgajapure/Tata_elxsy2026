"""Report generation for QoS experiments in HTML, Markdown, JSON, and CSV."""

from __future__ import annotations

import csv
import io
import json
from dataclasses import asdict
from typing import Any, Mapping


def generate_json_report(result_data: Mapping[str, Any]) -> str:
    return json.dumps(result_data, indent=2)


def generate_csv_report(result_data: Mapping[str, Any]) -> str:
    output = io.StringIO()
    writer = csv.writer(output)

    writer.writerow(["scenario_id", "scenario_name", "timestamp", "mode", "metric", "value", "unit"])
    sid = result_data.get("scenario_id", "")
    sname = result_data.get("scenario_name", "")
    ts = result_data.get("timestamp", "")

    comparisons = result_data.get("comparisons", {})
    for mode, metrics in comparisons.items():
        for k, v in metrics.items():
            unit = "ms" if "latency" in k or "rtt" in k or "jitter" in k else "Mbps" if "throughput" in k or "rate" in k else "%" if "loss" in k else "score" if "fairness" in k else "count"
            writer.writerow([sid, sname, ts, mode, k, v, unit])

    return output.getvalue()


def generate_markdown_report(result_data: Mapping[str, Any]) -> str:
    sid = result_data.get("scenario_id", "")
    sname = result_data.get("scenario_name", "")
    ts = result_data.get("timestamp", "")
    desc = result_data.get("description", "")
    comparisons = result_data.get("comparisons", {})
    summary = result_data.get("summary_text", "")
    env_info = result_data.get("environment", {})

    lines = [
        f"# Experiment Report: {sname}",
        f"**Scenario ID**: `{sid}` | **Date**: {ts}",
        "",
        f"### Objective",
        desc,
        "",
        "### Baseline vs. Adaptive QoS Comparison",
        "",
        "| Metric | No QoS (FIFO) | Static QoS | Adaptive QoS (TataElexy) | Improvement |",
        "|---|---|---|---|---|",
    ]

    no_qos = comparisons.get("no_qos", {})
    static_qos = comparisons.get("static_qos", {})
    adaptive = comparisons.get("adaptive_qos", {})

    all_keys = list(dict.fromkeys(list(no_qos) + list(static_qos) + list(adaptive)))
    for k in all_keys:
        v_no = no_qos.get(k, "N/A")
        v_st = static_qos.get(k, "N/A")
        v_ad = adaptive.get(k, "N/A")
        imp = "—"
        if isinstance(v_no, (int, float)) and isinstance(v_ad, (int, float)) and v_no != 0:
            if "rtt" in k or "latency" in k or "jitter" in k or "loss" in k:
                diff = ((v_no - v_ad) / v_no) * 100.0
                imp = f"▼ {diff:.1f}% reduction" if diff > 0 else f"▲ {abs(diff):.1f}%"
            elif "fairness" in k or "throughput" in k:
                diff = ((v_ad - v_no) / v_no) * 100.0
                imp = f"▲ +{diff:.1f}%" if diff > 0 else f"{diff:.1f}%"

        def fmt(x):
            return f"{x:.2f}" if isinstance(x, float) else str(x)

        label = k.replace("_", " ").title()
        lines.append(f"| **{label}** | {fmt(v_no)} | {fmt(v_st)} | {fmt(v_ad)} | {imp} |")

    lines.extend([
        "",
        "### Key Findings",
        summary or "Adaptive QoS protected high-priority latency while dynamically allocating surplus capacity.",
        "",
        "### Environment Notes",
        f"- **Execution Mode**: {env_info.get('execution_mode', 'Emulation / Simulated Workload')}",
        f"- **Platform**: {env_info.get('platform', 'Linux / Windows WSL')}",
        f"- **Kernel Enforcement**: {env_info.get('enforcement_backend', 'Dry-Run / Linux TC')}",
        "",
        "> [!NOTE]",
        "> Data presented here represents open, reproducible measurements generated by the TataElexy test suite.",
    ])

    return "\n".join(lines)


def generate_html_report(result_data: Mapping[str, Any]) -> str:
    md = generate_markdown_report(result_data)
    sname = result_data.get("scenario_name", "QoS Experiment Report")
    comparisons = result_data.get("comparisons", {})

